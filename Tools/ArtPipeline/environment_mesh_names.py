def preserve_mesh_names(asset, collection):
    expected = MESH_NAMES[asset]
    meshes = {obj.name: obj.data for obj in collection.all_objects if obj.type == "MESH"}
    if meshes.keys() != expected.keys():
        raise ValueError(f"Export mesh hierarchy changed for {asset}")
    for name, mesh in meshes.items():
        if mesh.name != expected[name]:
            mesh.rename(expected[name], mode="ALWAYS")
    assert all(mesh.name == expected[name] for name, mesh in meshes.items()), asset
